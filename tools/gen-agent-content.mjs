// Converts apps/web/src/content/faq.md (verbatim planner copy) → apps/web/src/agent/client/faq.ts and
// apps/web/src/agent/client/examples/*.html → apps/web/src/agent/client/examples.ts.
// Both outputs are committed. Run after editing either: `npm run gen` (repo root).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const client = join(repo, 'apps', 'web', 'src', 'agent', 'client');

// ---------- faq.md ----------
const md = readFileSync(join(repo, 'apps', 'web', 'src', 'content', 'faq.md'), 'utf8');
const sections = md.split(/^## /m).slice(1);
const intents = [];
let unknown = null;
let emojiBeats = [];
for (const sec of sections) {
  const [head, ...rest] = sec.split('\n');
  const id = head.trim();
  const body = rest.join('\n');
  if (id.startsWith('emoji_beats')) {
    emojiBeats = [...body.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
    continue;
  }
  const hintsLine = /^hints:\s*(.+)$/m.exec(body);
  const replyLine = /^→\s*(.*)$/m.exec(body);
  if (!replyLine) throw new Error(`faq.md: intent "${id}" has no reply line`);
  const reply = /`([^`]+)`/.exec(replyLine[1]);
  if (!reply) throw new Error(`faq.md: intent "${id}" reply is not in backticks`);
  const note = replyLine[1].replace(/`[^`]+`/, '').trim();
  if (id === 'unknown') {
    unknown = reply[1];
    continue;
  }
  if (!hintsLine) throw new Error(`faq.md: intent "${id}" has no hints`);
  const hints = hintsLine[1].split(',').map((h) => h.trim()).filter(Boolean);
  intents.push({ id, hints, reply: reply[1], ...(note ? { note } : {}) });
}
if (!unknown) throw new Error('faq.md: no unknown reply');
if (!emojiBeats.length) throw new Error('faq.md: no emoji_beats');

const preamble = md.split(/^## /m)[0].trim();

writeFileSync(
  join(client, 'faq.ts'),
  `// GENERATED by tools/gen-agent-content.mjs from content/faq.md (verbatim). Do not edit by hand.

export interface FaqIntent {
  /** section name in faq.md */
  id: string;
  /** trigger keywords/phrases, verbatim */
  hints: readonly string[];
  /** reply text with inline [[actions]], verbatim */
  reply: string;
  /** any note that followed the reply in faq.md */
  note?: string;
}

/** The rules paragraph at the top of faq.md (name capture, emoji-only, spell X). */
export const FAQ_RULES = ${JSON.stringify(preamble)};

export const FAQ_INTENTS: readonly FaqIntent[] = ${JSON.stringify(intents, null, 2)};

export const FAQ_UNKNOWN = ${JSON.stringify(unknown)};

export const EMOJI_BEATS: readonly string[] = ${JSON.stringify(emojiBeats)};
`,
);

// ---------- examples ----------
const META = {
  pomodoro: { title: 'Pomodoro timer', keywords: ['pomodoro', 'timer', 'focus', 'countdown', 'clock', 'stopwatch'] },
  landing: { title: 'Landing page', keywords: ['landing', 'homepage', 'marketing', 'startup', 'product page', 'saas', 'website'] },
  todo: { title: 'Todo list', keywords: ['todo', 'to-do', 'to do', 'task', 'tasks', 'checklist', 'list'] },
  weather: { title: 'Weather card', keywords: ['weather', 'forecast', 'temperature', 'rain', 'climate'] },
  habits: { title: 'Habit tracker', keywords: ['habit', 'habits', 'tracker', 'streak', 'routine', 'goals'] },
  birthday: { title: 'Birthday card', keywords: ['birthday', 'card', 'greeting', 'party', 'celebrate', 'anniversary'] },
};
const order = Object.keys(META);
const files = readdirSync(join(client, 'examples')).filter((f) => f.endsWith('.html'));
for (const f of files) if (!META[f.replace(/\.html$/, '')]) throw new Error(`examples/${f} has no META entry`);
const examples = order.map((id) => {
  const html = readFileSync(join(client, 'examples', `${id}.html`), 'utf8');
  const bytes = Buffer.byteLength(html);
  if (bytes > 40_000) throw new Error(`examples/${id}.html is ${bytes} bytes (> 40 kB)`);
  if (/https?:\/\//.test(html.replace(/http:\/\/www\.w3\.org\/2000\/svg/g, ''))) throw new Error(`examples/${id}.html references a URL`);
  return { id, ...META[id], html };
});

writeFileSync(
  join(client, 'examples.ts'),
  `// GENERATED by tools/gen-agent-content.mjs from examples/*.html. Do not edit by hand.
// Loaded lazily (dynamic import) so the site's main bundle doesn't carry ~${Math.round(examples.reduce((n, e) => n + e.html.length, 0) / 1000)} kB of HTML.

export interface ExampleApp {
  id: string;
  title: string;
  keywords: readonly string[];
  html: string;
}

export const EXAMPLES: readonly ExampleApp[] = ${JSON.stringify(examples, null, 2)};
`,
);

writeFileSync(
  join(client, 'examples-meta.ts'),
  `// GENERATED by tools/gen-agent-content.mjs. Do not edit by hand.
// Titles of the prebuilt example apps, without their HTML (for the "welcome back" line).

export const EXAMPLE_TITLES: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(examples.map((e) => [e.id, e.title])), null, 2)};
`,
);

console.log(`faq: ${intents.length} intents, ${emojiBeats.length} emoji beats; examples: ${examples.map((e) => `${e.id} ${(e.html.length / 1000).toFixed(1)}kB`).join(', ')}`);
